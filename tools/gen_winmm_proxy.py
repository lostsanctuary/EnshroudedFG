"""Generate winmm.dll proxy sources from the system winmm.dll export table.

Outputs (into src/proxy/generated/):
  winmm.def           - module definition with every named export at its original ordinal
  winmm_stubs.asm     - MASM x64 jump stubs: each export jumps through g_winmm_table[i]
  winmm_exports.inc   - C++ list of export names (index matches the jump table)

Usage: python -I tools/gen_winmm_proxy.py [path-to-winmm.dll] [out-dir]
"""
import os
import struct
import sys


def read_exports(path):
    data = open(path, "rb").read()
    pe = struct.unpack_from("<I", data, 0x3C)[0]
    if data[pe:pe + 4] != b"PE\0\0":
        raise ValueError("not a PE file")
    num_sections = struct.unpack_from("<H", data, pe + 6)[0]
    opt_size = struct.unpack_from("<H", data, pe + 20)[0]
    opt = pe + 24
    if struct.unpack_from("<H", data, opt)[0] != 0x20B:
        raise ValueError("expected PE32+ (x64)")
    export_rva, _ = struct.unpack_from("<II", data, opt + 112)
    sections = []
    sec = opt + opt_size
    for i in range(num_sections):
        vsize, va, rawsize, rawptr = struct.unpack_from("<IIII", data, sec + i * 40 + 8)
        sections.append((va, max(vsize, rawsize), rawptr))

    def off(rva):
        for va, size, raw in sections:
            if va <= rva < va + size:
                return rva - va + raw
        raise ValueError(f"rva {rva:#x} not in any section")

    e = off(export_rva)
    base, nfuncs, nnames, funcs, names, ords = struct.unpack_from("<IIIIII", data, e + 16)
    exports = []
    for i in range(nnames):
        name_rva = struct.unpack_from("<I", data, off(names) + i * 4)[0]
        idx = struct.unpack_from("<H", data, off(ords) + i * 2)[0]
        n = off(name_rva)
        name = data[n:data.index(b"\0", n)].decode("ascii")
        exports.append((base + idx, name))
    named_ordinals = {o for o, _ in exports}
    unnamed = [base + i for i in range(nfuncs)
               if base + i not in named_ordinals
               and struct.unpack_from("<I", data, off(funcs) + i * 4)[0] != 0]
    return sorted(exports), unnamed


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else r"C:\Windows\System32\winmm.dll"
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
        os.path.dirname(__file__), "..", "src", "proxy", "generated")
    os.makedirs(out, exist_ok=True)
    exports, unnamed = read_exports(src)

    with open(os.path.join(out, "winmm.def"), "w", newline="\n") as f:
        f.write("LIBRARY winmm\nEXPORTS\n")
        for i, (ordinal, name) in enumerate(exports):
            f.write(f"    {name}=proxy_stub_{i} @{ordinal}\n")
        for ordinal in unnamed:
            f.write(f"    proxy_ord_{ordinal}=proxy_ord_stub_{ordinal} @{ordinal} NONAME\n")

    with open(os.path.join(out, "winmm_stubs.asm"), "w", newline="\n") as f:
        f.write("; generated by tools/gen_winmm_proxy.py - do not edit\n")
        f.write("EXTERN g_winmm_table:QWORD\nEXTERN g_winmm_ord_table:QWORD\n.code\n")
        for i, (_, name) in enumerate(exports):
            f.write(f"proxy_stub_{i} PROC  ; {name}\n"
                    f"    jmp qword ptr [g_winmm_table + {i * 8}]\n"
                    f"proxy_stub_{i} ENDP\n")
        for j, ordinal in enumerate(unnamed):
            f.write(f"proxy_ord_stub_{ordinal} PROC\n"
                    f"    jmp qword ptr [g_winmm_ord_table + {j * 8}]\n"
                    f"proxy_ord_stub_{ordinal} ENDP\n")
        f.write("END\n")

    with open(os.path.join(out, "winmm_exports.inc"), "w", newline="\n") as f:
        f.write("// generated by tools/gen_winmm_proxy.py - do not edit\n")
        f.write("static const char* const kWinmmExportNames[] = {\n")
        for _, name in exports:
            f.write(f'    "{name}",\n')
        f.write("};\nstatic const unsigned short kWinmmUnnamedOrdinals[] = {\n")
        for ordinal in unnamed or [0]:
            f.write(f"    {ordinal},\n")
        f.write(f"}};\nstatic const unsigned kWinmmUnnamedCount = {len(unnamed)};\n")

    print(f"{len(exports)} named exports, {len(unnamed)} ordinal-only exports -> {os.path.abspath(out)}")


if __name__ == "__main__":
    main()
